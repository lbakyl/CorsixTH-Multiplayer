#!/usr/bin/env python3
"""Turn the multiplayer icons (scripts/multiplayer/icons/*.png, pixel art by
MATROFTT) into CorsixTH/Lua/mp_icons.lua, which the game draws with
MultiplayerSession.drawIcon. The game cannot load PNG files, so each icon
becomes a list of one-pixel-high runs of one colour.

Usage: python3 scripts/multiplayer/make_mp_icons.py   (needs Pillow)
Run it again after changing an icon, and commit both.
"""
import os
import sys

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SOURCE = os.path.join(ROOT, "scripts", "multiplayer", "icons")
TARGET = os.path.join(ROOT, "CorsixTH", "Lua", "mp_icons.lua")

